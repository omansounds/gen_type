// A filled convex disk (used for dots: period, i/j tittles, colon, etc.).
export function disk(cx, cy, r, steps = 20) {
  const out = [];
  for (let i = 0; i < steps; i++) {
    const a = (i / steps) * Math.PI * 2;
    out.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  return out;
}

// The left-hand half of an ellipse (mirror of geometry.rightBowl) for d, q.
function leftBowl(x0, yTop, yBot, extent, steps = 24) {
  const cy = (yTop + yBot) / 2;
  const ry = (yTop - yBot) / 2;
  const rx = x0 - extent;
  return arc(x0, cy, rx, ry, 90, 270, steps);
}

